from pathlib import Path
from playwright.sync_api import sync_playwright

root = Path(__file__).parent
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=r'C:\Program Files\Google\Chrome\Application\chrome.exe', headless=True)
    page = browser.new_page(viewport={'width': 1680, 'height': 1070}, device_scale_factor=1)
    errors=[]
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto((root/'index.html').as_uri())
    page.wait_for_load_state('networkidle')
    page.screenshot(path=str(root/'详情页-四种身份.png'), full_page=True)
    staff=page.locator('#phone-staff')
    staff.locator('.footer-actions [data-action="entry"]').click()
    staff.locator('[data-action="save-entry"]').click()
    staff.locator('[data-action="confirm-entry"]').click()
    assert staff.locator('.stats').inner_text().startswith('27')
    admin=page.locator('#phone-admin')
    admin.locator('.footer-actions [data-action="review"]').click()
    admin.locator('[data-action="publish"]').click()
    assert '请先核对' in admin.locator('#review-error').inner_text()
    admin.locator('#review-check').check()
    admin.locator('[data-action="publish"]').click()
    assert 'v2' in admin.inner_text()
    owner=page.locator('#phone-owner')
    owner.locator('[data-action="editgrant"]').click()
    owner.locator('[data-action="revoke"]').click()
    owner.locator('[data-action="confirm-revoke"]').click()
    assert '已收回' in owner.inner_text()
    page.locator('#phase').select_option('ended')
    staff.locator('.footer-actions [data-action="entry"]').click()
    assert '录入关闭' in staff.locator('.sheet').inner_text()
    page.reload()
    page.locator('#phone-user .entry-card').click()
    assert '00:37:00.75' in page.locator('#phone-user').inner_text()
    page.screenshot(path=str(root/'详情页-成绩与工作台.png'), full_page=True)
    page.locator('#phone-staff .footer-actions [data-action="entry"]').click()
    page.locator('#phone-admin .footer-actions [data-action="review"]').click()
    page.locator('#phone-owner .footer-actions [data-action="grant"]').click()
    page.screenshot(path=str(root/'详情页-操作面板.png'),full_page=True)
    page.locator('#focus').select_option('user')
    page.set_viewport_size({'width':390,'height':1050})
    page.screenshot(path=str(root/'详情页-手机成绩.png'),full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.set_viewport_size({'width':320,'height':1000})
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    assert page.locator('#phone-user').evaluate('(e)=>e.scrollWidth<=e.clientWidth')
    assert not errors, errors
    print('PASS: entry confirmation, review gate, publication, revoke, ended read-only, personal scores, 390/320px overflow; no JS errors')
    browser.close()
